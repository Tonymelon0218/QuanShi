void Mod_LvdsTx_GetLvdsInClk()
{
    u8 ucIndex = 0;
    u32 ulInclk = 0;
    Drv_System_FmSet(TOP_FM, 0x14); // AD_DSCTX_DSC_OUT_CLK TX_FM
    Ocm_Delay1ms(5);

    for (; ucIndex < 5; ucIndex++)
    {
        if (STABLE == Drv_System_FmStbGet(TOP_FM))
        {
            ulInclk = Drv_System_FmGet(TOP_FM, 0);
            break;
        }
        Ocm_Delay1ms(1);
    }
    g_stLvdsTx.ulLvdsTxInputClk = ulInclk;
}

