void Mod_LvdsTx_SetState(u8 ucState)
{
    if (ucState != g_stLvdsTx.ucTxState)
    {
        g_stLvdsTx.ucTxStateChangeFlag = TRUE;
        g_stLvdsTx.ucTxState = ucState;
        LTLog(LOG_DEBUG, "TxState = 0x%02bx", ucState);

        if (ucState == STATE_LVDSTX_VIDEO_OUT_5)
        {
            TX_Event_Set(TX_VIDEO_ON_EVENT_3);
        }
    }
}

